/** One plate on the globe, one cell in the index. Photographs and videos alike. */
export type GalleryItem = {
  id: string;
  kind: 'photo' | 'video';
  group: GroupId;
  /** Album id for a photograph; the video's section for a recording. */
  albumId: string;
  section: EventSection;
  venueId?: string;
  batches?: string[];
  title: string;
  /** Album and date for a photograph; the destination for a recording. */
  subtitle: string;
  /** 512px-long-edge texture, whole image, nothing cropped */
  plate: string;
  /** Full-size image (or the recording's poster) */
  src: string;
  width: number;
  height: number;
  alt: string;
  onGlobe: boolean;
  /** Videos only */
  href?: string;
};

/** The globe's name for it. */
export type GlobeItem = GalleryItem;

function photoItem([key, albumId, width, height, onGlobe]: (typeof RAW_PHOTOS)[number]): GalleryItem {
  const a = album(albumId);
  const date = albumDate(a);
  const isClass = a.group === 'classes';
  const title = isClass ? a.batches!.map((c) => `${c} · ${batchLabel(c)}`).join('  /  ') : a.title;
  const venue = a.venueId ? VENUE_NAME.get(a.venueId) : undefined;
  return {
    id: key,
    kind: 'photo',
    group: a.group,
    albumId,
    section: a.section,
    venueId: a.venueId,
    batches: a.batches,
    title,
    subtitle: isClass ? `${venue}` : date ? `${a.title} · ${date}` : a.title,
    plate: platePath(key),
    src: `/img/gallery/${key}.jpg`,
    width,
    height,
    alt: isClass
      ? `Students in class at ${venue}, batch ${a.batches!.join(' and ')}`
      : `A photograph from ${a.title}${date ? `, ${date}` : ''}`,
    onGlobe,
  };
}

function videoItem(video: (typeof VIDEOS)[number]): GalleryItem {
  const poster = videoPoster(video);
  return {
    id: `v-${video.id}`,
    kind: 'video',
    group: 'videos',
    albumId: 'videos',
    section: video.section,
    title: videoLabel(video),
    subtitle: `${sectionMeta(video.section).heading} · opens YouTube`,
    plate: platePath(video.plateKey),
    src: poster.src,
    width: poster.width,
    height: poster.height,
    alt: poster.alt,
    onGlobe: true,
    href: youtubeHref(video),
  };
}

export const PHOTOS: GalleryItem[] = RAW_PHOTOS.map(photoItem);
export const RECORDINGS: GalleryItem[] = VIDEOS.map(videoItem);
export const ALL_ITEMS: GalleryItem[] = [...PHOTOS, ...RECORDINGS];

/**
 * The globe: the curated photographs with the videos spread through them.
 *
 * Plates are laid out by index along a Fibonacci spiral, so a contiguous block of
 * recordings would land as one patch on one face of the sphere. Interleaving at a
 * regular stride scatters them, so whichever way the sphere is turned there is
 * something to watch in view. The photographs keep album order otherwise, so
 * neighbouring plates come from the same stage.
 */
export function globeItems(): GalleryItem[] {
  const photos = PHOTOS.filter((p) => p.onGlobe);
  const videos = RECORDINGS;
  const stride = Math.max(1, Math.floor((photos.length + videos.length) / videos.length));
  const out: GalleryItem[] = [];
  let next = 0;
  photos.forEach((photo, i) => {
    out.push(photo);
    if (next < videos.length && (i + 1) % stride === 0) {
      out.push(videos[next]);
      next += 1;
    }
  });
  out.push(...videos.slice(next));
  return out;
}

export const GLOBE_ITEMS = globeItems();

