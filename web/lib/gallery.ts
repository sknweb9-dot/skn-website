const BATCH_INFO = new Map(allBatches().map(({ batch, programme }) => [batch.code, { batch, programme }]));
const VENUE_NAME = new Map(VENUES.map((v) => [v.id, v.name]));

/** "Level 3 · Mon & Fri", from the same data as the Locations page. */
export function batchLabel(code: string): string {
  const info = BATCH_INFO.get(code);
  if (!info) return code;
  return `${info.programme.label} · ${formatDays(info.batch.days)}`;
}

function classAlbum(a: (typeof CLASS_ALBUMS)[number]): Album {
  const venue = VENUE_NAME.get(a.venueId) ?? a.venueId;
  return {
    id: a.id,
    group: 'classes',
    title: `${venue}: ${a.batches.join(' & ')}`,
    section: 'studio',
    venueId: a.venueId,
    batches: a.batches,
  };
}

export const ALBUMS: Album[] = [...CLASS_ALBUMS.map(classAlbum), ...EVENT_ALBUMS];
const ALBUM_BY_ID = new Map(ALBUMS.map((a) => [a.id, a]));

export function album(id: string): Album {
  const found = ALBUM_BY_ID.get(id);
  if (!found) throw new Error(`Unknown gallery album: ${id}`);
  return found;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

export function albumDate(a: Album): string | null {
  if (a.dateText) return a.dateText;
  if (!a.date) return null;
  const [year, month] = a.date.split('-');
  return month ? `${MONTHS[Number(month) - 1]} ${year}` : year;
}

