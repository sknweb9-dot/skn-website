/**
 * The gallery: every photograph and video, the albums they belong to, and
 * the filters that find them.
 *
 * WHERE THE WORDS COME FROM
 * -------------------------
 * Album names and dates are the academy's own: the folder names in its archive
 * and the Events list in `Website Contents.docx`. No photograph has a title or a
 * date that nobody supplied. Where the two sources disagree about a date (the
 * Samarpanam Festival: the docx says 30 September 2025, the folder says October
 * 2025) the album shows the year alone rather than choosing. A photograph's
 * caption is its album: the archive does not say who is in which picture, and
 * this file does not guess.
 *
 * The image list itself, `gallery.data.ts`, is generated by
 * `_research/make_gallery_assets.py`; this file is the part a person edits.
 *
 * TWO SETS
 * --------
 * The index lists every photograph, so a parent can find their child. The globe
 * carries a curated subset (`onGlobe`) plus the videos, because a sphere of
 * two hundred plates stops being legible. A filter applies to both: the globe
 * dims what does not match, the index hides it.
 */

