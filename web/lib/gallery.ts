export type GalleryFilter = {
  group: GroupId | null;
  /** An event album, or a class album when `venue`/`batch` are not used */
  album: string | null;
  venue: string | null;
  batch: string | null;
  query: string;
};

export const NO_FILTER: GalleryFilter = { group: null, album: null, venue: null, batch: null, query: '' };

export function isFiltered(f: GalleryFilter): boolean {
  return Boolean(f.group || f.album || f.venue || f.batch || f.query.trim());
}

export function matches(item: GalleryItem, f: GalleryFilter): boolean {
  if (f.group && item.group !== f.group) return false;
  if (f.album && item.albumId !== f.album) return false;
  if (f.venue && item.venueId !== f.venue) return false;
  if (f.batch && !item.batches?.includes(f.batch)) return false;
  const needle = f.query.trim().toLowerCase();
  if (needle) {
    const hay = [item.title, item.subtitle, item.venueId ? VENUE_NAME.get(item.venueId) : '', ...(item.batches ?? [])]
      .join(' ')
      .toLowerCase();
    if (!hay.includes(needle)) return false;
  }
  return true;
}

export type FilterOption = { id: string; label: string; detail?: string; count: number };

const count = (pred: (i: GalleryItem) => boolean) => ALL_ITEMS.filter(pred).length;

export function groupOptions(): (FilterOption & { id: GroupId })[] {
  return GROUPS.map((g) => ({ id: g.id, label: g.label, count: count((i) => i.group === g.id) }));
}

/** The second row: what can be chosen inside the selected group. */
export function subOptions(group: GroupId | null): { kind: 'album' | 'venue'; options: FilterOption[] } | null {
  if (!group || group === 'videos') return null;
  if (group === 'classes') {
    const venues = VENUES.filter((v) => CLASS_ALBUMS.some((a) => a.venueId === v.id));
    return {
      kind: 'venue',
      options: venues.map((v) => ({ id: v.id, label: v.name, count: count((i) => i.venueId === v.id) })),
    };
  }
  return {
    kind: 'album',
    options: ALBUMS.filter((a) => a.group === group).map((a) => ({
      id: a.id,
      label: a.title,
      detail: albumDate(a) ?? undefined,
      count: count((i) => i.albumId === a.id),
    })),
  };
}

/** The third row, for classes: the batches at the chosen venue. */
export function batchOptions(venueId: string | null): FilterOption[] {
  if (!venueId) return [];
  const codes = CLASS_ALBUMS.filter((a) => a.venueId === venueId).flatMap((a) => a.batches);
  return codes.map((code) => ({
    id: code,
    label: code,
    detail: batchLabel(code),
    count: count((i) => i.batches?.includes(code) ?? false),
  }));
}

// ---------------------------------------------------------------------------
// The index: items grouped by album, in reading order
// ---------------------------------------------------------------------------

export type IndexSection = { id: string; title: string; detail: string | null; group: GroupId; items: GalleryItem[] };

export function indexSections(items: GalleryItem[]): IndexSection[] {
  const sections: IndexSection[] = [];
  for (const g of GROUPS) {
    if (g.id === 'videos') {
      const vids = items.filter((i) => i.kind === 'video');
      if (vids.length) sections.push({ id: 'videos', title: 'Videos', detail: 'Open on YouTube', group: 'videos', items: vids });
      continue;
    }
    for (const a of ALBUMS.filter((x) => x.group === g.id)) {
      const inAlbum = items.filter((i) => i.albumId === a.id);
      if (!inAlbum.length) continue;
      const detail =
        a.group === 'classes'
          ? a.batches!.map(batchLabel).join('  /  ')
          : albumDate(a);
      sections.push({ id: a.id, title: a.title, detail, group: a.group, items: inAlbum });
    }
  }
  return sections;
}

// ---------------------------------------------------------------------------
// Links a parent can keep: /gallery?group=classes&venue=adroit&batch=AD1
// ---------------------------------------------------------------------------

export function filterToQuery(f: GalleryFilter): string {
  const p = new URLSearchParams();
  if (f.group) p.set('group', f.group);
  if (f.album) p.set('album', f.album);
  if (f.venue) p.set('venue', f.venue);
  if (f.batch) p.set('batch', f.batch);
  if (f.query.trim()) p.set('q', f.query.trim());
  return p.toString();
}

export function queryToFilter(search: string): GalleryFilter {
  const p = new URLSearchParams(search);
  const group = p.get('group') as GroupId | null;
  const valid = group && GROUPS.some((g) => g.id === group) ? group : null;
  const albumId = p.get('album');
  const venue = p.get('venue');
  const batch = p.get('batch');
  return {
    group: valid,
    album: albumId && ALBUM_BY_ID.has(albumId) ? albumId : null,
    venue: venue && VENUE_NAME.has(venue) ? venue : null,
    batch: batch && BATCH_INFO.has(batch) ? batch : null,
    query: (p.get('q') ?? '').slice(0, 80),
  };
}

